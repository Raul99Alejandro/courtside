// Writes packages/shared/src/config.generated.ts from ../cdk-outputs.json (the deployed stack's public URLs).
// Usage: node scripts/gen-config.mjs   (re-run after a deploy that changes the URLs)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const out = JSON.parse(readFileSync(new URL('../cdk-outputs.json', root), 'utf8')).Courtside;
const strip = (u) => u.replace(/\/$/, '');
const body = `// Generated by scripts/gen-config.mjs from cdk-outputs.json. These URLs are public; do not edit by hand.
export const GENERATED_CONFIG = {
  httpApiUrl: ${JSON.stringify(strip(out.HttpApiUrl))},
  wsUrl: ${JSON.stringify(strip(out.WsUrl))},
  siteUrl: ${JSON.stringify(strip(out.SiteUrl))},
};
`;
const file = new URL('packages/shared/src/config.generated.ts', root);
writeFileSync(file, body);
console.log('wrote', fileURLToPath(file));
